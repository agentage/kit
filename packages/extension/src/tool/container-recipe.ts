export const CONTAINER_PORT = 8080;

// The volume holds the store folder, so its <dir>.lock sibling persists with it.
export const DATA_VOLUME = '/data';
export const STORE_DIR = `${DATA_VOLUME}/store`;
// git-daemon brings git http-backend, which a part serving smart HTTP spawns.
export const GIT_INSTALL = 'RUN apk add --no-cache git git-daemon';
export const DATA_VOLUME_LINES = [
  `RUN mkdir -p ${DATA_VOLUME} && chown node:node ${DATA_VOLUME}`,
  `VOLUME ${DATA_VOLUME}`,
];

const HEALTH_PROBE =
  `fetch('http://127.0.0.1:'+(process.env.PORT||${CONTAINER_PORT})+'/health')` +
  '.then((r) => process.exit(r.status === 200 || r.status === 503 ? 0 : 1), () => process.exit(1))';

const DEPS = [
  '# syntax=docker/dockerfile:1',
  '# Generated by @agentage/extension build --container. Extension authors never write a Dockerfile.',
  'FROM node:26-alpine AS deps',
  'WORKDIR /app',
  'COPY deps/ ./',
  'RUN npm ci --omit=dev --no-audit --no-fund',
  '',
];

// PGlite is an optional peer and a dev dependency of an extension, so npm ci --omit=dev drops it.
const pgliteStage = (version: string) => [
  'FROM node:26-alpine AS pglite',
  'WORKDIR /pglite',
  `RUN npm install --no-audit --no-fund --no-package-lock @electric-sql/pglite@${version}`,
  '',
];

const runnerEnv = (store: boolean) => [
  'FROM node:26-alpine AS runner',
  'ARG COMMIT_SHA',
  'ARG BUILD_TIME',
  'ENV NODE_ENV=production \\',
  `    PORT=${CONTAINER_PORT} \\`,
  '    AGENTAGE_HOST_BIND=all \\',
  '    AGENTAGE_DRAIN_MS=8000 \\',
  ...(store ? [`    AGENTAGE_DATA_DIR=${STORE_DIR} \\`] : []),
  '    COMMIT_SHA=$COMMIT_SHA \\',
  '    BUILD_TIME=$BUILD_TIME',
];

interface Stores {
  pglite?: string;
  // A git store: the git binary for the part, its repos on the /data volume.
  git?: boolean;
}

const runner = ({ pglite, git }: Stores) => [
  ...runnerEnv(pglite !== undefined || Boolean(git)),
  ...(git ? [GIT_INSTALL] : []),
  'WORKDIR /app',
  'COPY --from=deps /app/node_modules ./node_modules',
  ...(pglite !== undefined
    ? [
        'COPY --from=pglite /pglite/node_modules/@electric-sql/pglite ./node_modules/@electric-sql/pglite',
      ]
    : []),
  'COPY app/ ./',
  ...(pglite !== undefined || git ? DATA_VOLUME_LINES : []),
  'USER node',
  `EXPOSE ${CONTAINER_PORT}`,
  `HEALTHCHECK --interval=10s --timeout=3s --start-period=15s --retries=3 CMD ["node", "-e", "${HEALTH_PROBE}"]`,
  'CMD ["node", "node_modules/@agentage/extension/dist/host/main.js"]',
  '',
];

// The one image of an extension: the kit host in one process; pglite is set for a postgres store.
export const containerRecipe = (stores: Stores): string =>
  [...DEPS, ...(stores.pglite ? pgliteStage(stores.pglite) : []), ...runner(stores)].join('\n');
