// The nav icons an app can name: all of lucide is 800 KB or 4700 chunks; a new name is one line.
const COMMON: Record<string, LucideIcon> = {
  activity: Activity,
  archive: Archive,
  bell: Bell,
  bomb: Bomb,
  book: Book,
  box: Box,
  brain: Brain,
  calendar: Calendar,
  'chart-line': ChartLine,
  cloud: Cloud,
  database: Database,
  'file-text': FileText,
  folder: Folder,
  'git-branch': GitBranch,
  globe: Globe,
  house: House,
  'key-round': KeyRound,
  'layout-dashboard': LayoutDashboard,
  list: List,
  mail: Mail,
  'message-square': MessageSquare,
  network: Network,
  puzzle: Puzzle,
  radar: Radar,
  search: Search,
  server: Server,
  settings: Settings,
  shield: Shield,
  'shopping-cart': ShoppingCart,
  store: Store,
  terminal: Terminal,
  users: Users,
  zap: Zap,
};

export const APP_ICONS = Object.keys(COMMON);

// A nav row icon by its lucide name (`agentage.app.icon`); a name outside the set shows `box`.
export const AppIcon = ({ name = 'box' }: { name?: string }) => {
  const Icon = COMMON[name] ?? Box;
  return <Icon className="i" aria-hidden="true" data-icon={name} />;
};
